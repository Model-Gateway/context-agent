//! Memory record types (spec §9.2, §9.3).

use ctx_core::{MemoryId, RepositoryId, TaskId, Timestamp};
use ctx_storage::MemoryRow;
use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum MemoryCategory {
    Task,
    ProjectKnowledge,
    Episodic,
    ExecutionHistory,
}

impl MemoryCategory {
    pub fn as_str(&self) -> &'static str {
        match self {
            MemoryCategory::Task => "task",
            MemoryCategory::ProjectKnowledge => "project_knowledge",
            MemoryCategory::Episodic => "episodic",
            MemoryCategory::ExecutionHistory => "execution_history",
        }
    }

    pub fn parse(s: &str) -> Option<Self> {
        Some(match s {
            "task" => MemoryCategory::Task,
            "project_knowledge" => MemoryCategory::ProjectKnowledge,
            "episodic" => MemoryCategory::Episodic,
            "execution_history" => MemoryCategory::ExecutionHistory,
            _ => return None,
        })
    }
}

/// Evidence levels, weakest to strongest (spec §9.3).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum VerificationStatus {
    /// Generated by the model without confirmation.
    Hypothesis,
    /// Stated by the user.
    UserProvided,
    /// Observed directly in repository source.
    SourceDerived,
    /// Confirmed by a tool result (command output, git, etc.).
    ToolConfirmed,
    /// Confirmed by a passing test run.
    TestValidated,
}

impl VerificationStatus {
    pub fn as_str(&self) -> &'static str {
        match self {
            VerificationStatus::Hypothesis => "hypothesis",
            VerificationStatus::UserProvided => "user_provided",
            VerificationStatus::SourceDerived => "source_derived",
            VerificationStatus::ToolConfirmed => "tool_confirmed",
            VerificationStatus::TestValidated => "test_validated",
        }
    }

    pub fn parse(s: &str) -> Option<Self> {
        Some(match s {
            "hypothesis" => VerificationStatus::Hypothesis,
            "user_provided" => VerificationStatus::UserProvided,
            "source_derived" => VerificationStatus::SourceDerived,
            "tool_confirmed" => VerificationStatus::ToolConfirmed,
            "test_validated" => VerificationStatus::TestValidated,
            _ => return None,
        })
    }

    /// Whether the fact may be presented as current authoritative knowledge.
    pub fn is_trusted(&self) -> bool {
        !matches!(self, VerificationStatus::Hypothesis)
    }

    /// Relevance weight used when ranking memories.
    pub fn weight(&self) -> f64 {
        match self {
            VerificationStatus::Hypothesis => 0.5,
            VerificationStatus::UserProvided => 1.0,
            VerificationStatus::SourceDerived => 0.9,
            VerificationStatus::ToolConfirmed => 1.0,
            VerificationStatus::TestValidated => 1.1,
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum EvidenceKind {
    Source,
    ToolResult,
    Test,
    User,
    Model,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct EvidenceReference {
    pub kind: EvidenceKind,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub path: Option<String>,
    /// File hash at the time of observation, for invalidation.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub hash: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub detail: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub event_id: Option<i64>,
}

impl EvidenceReference {
    pub fn source(path: impl Into<String>, hash: Option<String>) -> Self {
        Self { kind: EvidenceKind::Source, path: Some(path.into()), hash, detail: None, event_id: None }
    }

    pub fn tool(detail: impl Into<String>, event_id: Option<i64>) -> Self {
        Self { kind: EvidenceKind::ToolResult, path: None, hash: None, detail: Some(detail.into()), event_id }
    }

    pub fn test(detail: impl Into<String>) -> Self {
        Self { kind: EvidenceKind::Test, path: None, hash: None, detail: Some(detail.into()), event_id: None }
    }

    pub fn user() -> Self {
        Self { kind: EvidenceKind::User, path: None, hash: None, detail: None, event_id: None }
    }

    pub fn model() -> Self {
        Self { kind: EvidenceKind::Model, path: None, hash: None, detail: None, event_id: None }
    }
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct MemoryRecord {
    pub id: MemoryId,
    pub repository_id: RepositoryId,
    pub task_id: Option<TaskId>,
    pub category: MemoryCategory,
    pub content: String,
    pub evidence: Vec<EvidenceReference>,
    pub verification: VerificationStatus,
    pub tags: Vec<String>,
    pub created_at: Timestamp,
    pub updated_at: Timestamp,
    pub invalidated: bool,
    pub invalidation_reason: Option<String>,
}

impl MemoryRecord {
    pub fn new(repository_id: RepositoryId, category: MemoryCategory, content: impl Into<String>, verification: VerificationStatus) -> Self {
        let now = ctx_core::now();
        Self {
            id: MemoryId::new(),
            repository_id,
            task_id: None,
            category,
            content: content.into(),
            evidence: Vec::new(),
            verification,
            tags: Vec::new(),
            created_at: now,
            updated_at: now,
            invalidated: false,
            invalidation_reason: None,
        }
    }

    pub fn with_task(mut self, task_id: TaskId) -> Self {
        self.task_id = Some(task_id);
        self
    }

    pub fn with_evidence(mut self, evidence: EvidenceReference) -> Self {
        self.evidence.push(evidence);
        self
    }

    pub fn with_tags<I: IntoIterator<Item = S>, S: Into<String>>(mut self, tags: I) -> Self {
        self.tags.extend(tags.into_iter().map(Into::into));
        self
    }

    /// Paths referenced by evidence.
    pub fn evidence_paths(&self) -> impl Iterator<Item = &str> {
        self.evidence.iter().filter_map(|e| e.path.as_deref())
    }

    /// Whether this record may be supplied as current knowledge.
    pub fn is_current(&self) -> bool {
        !self.invalidated && self.verification.is_trusted()
    }

    pub fn to_row(&self) -> MemoryRow {
        MemoryRow {
            id: self.id.to_string(),
            repository_id: self.repository_id.to_string(),
            task_id: self.task_id.as_ref().map(|t| t.to_string()),
            category: self.category.as_str().to_string(),
            content: self.content.clone(),
            evidence: serde_json::to_value(&self.evidence).unwrap_or(serde_json::Value::Array(vec![])),
            verification: self.verification.as_str().to_string(),
            tags: self.tags.join(" "),
            created_at: self.created_at,
            updated_at: self.updated_at,
            invalidated: self.invalidated,
            invalidation_reason: self.invalidation_reason.clone(),
        }
    }

    pub fn from_row(row: MemoryRow) -> Self {
        Self {
            id: MemoryId::from_string(row.id),
            repository_id: RepositoryId::from_string(row.repository_id),
            task_id: row.task_id.map(TaskId::from_string),
            category: MemoryCategory::parse(&row.category).unwrap_or(MemoryCategory::ProjectKnowledge),
            content: row.content,
            evidence: serde_json::from_value(row.evidence).unwrap_or_default(),
            verification: VerificationStatus::parse(&row.verification).unwrap_or(VerificationStatus::Hypothesis),
            tags: row.tags.split_whitespace().map(|s| s.to_string()).collect(),
            created_at: row.created_at,
            updated_at: row.updated_at,
            invalidated: row.invalidated,
            invalidation_reason: row.invalidation_reason,
        }
    }
}
