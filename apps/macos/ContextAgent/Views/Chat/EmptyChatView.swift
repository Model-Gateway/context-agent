import SwiftUI
import AppKit

/// The empty chat (reference-home.png): halftone band, ✳, "Where should we
/// begin?", the composer for the project's pending draft, the generated
/// starter suggestions and the index card (or the Connect-a-model card while no API key is set).
struct EmptyChatView: View {
    var project: ProjectState

    @Environment(AppState.self) private var appState

    init(project: ProjectState) {
        self.project = project
    }

    var body: some View {
        GeometryReader { geometry in
            ScrollView(.vertical) {
                VStack(spacing: 0) {
                    HalftoneHeader()
                    Spacer(minLength: 24)
                    column
                        .frame(maxWidth: Theme.Metrics.contentMaxWidth)
                        .padding(.horizontal, 24)
                    Spacer(minLength: 24)
                    // Sit slightly above the geometric centre, like the reference.
                    Color.clear.frame(height: 56)
                }
                .frame(maxWidth: .infinity, minHeight: geometry.size.height)
            }
        }
        .background(Theme.canvas)
    }

    private var column: some View {
        VStack(spacing: 24) {
            VStack(spacing: 14) {
                Icons.LogoView()
                Text("Where should we begin?")
                    .font(Theme.Font.title)
                    .foregroundStyle(Theme.textPrimary)
                    .accessibilityAddTraits(.isHeader)
            }
            ComposerView(draftFor: project)
            starterList
            if appState.needsAPIKey {
                ConnectModelCard()
            } else {
                IndexCard(project: project)
            }
        }
    }

    /// Generated by `suggest/starters` (AppState.loadStarters), a skeleton
    /// while the first answer is on its way. Re-asked when the empty chat
    /// appears for another project or the backend becomes ready.
    private var starterList: some View {
        StarterList(starters: project.starters, loading: project.startersLoading, insert: insert)
            .task(id: StarterLoadKey(projectId: project.id, ready: appState.connection.isReady, needsKey: appState.needsAPIKey)) {
                appState.loadStarters(for: project)
            }
    }

    /// Puts the prompt into the project's empty-state draft and focuses the composer.
    private func insert(_ prompt: String) {
        appState.pendingDraft[project.id] = prompt
        appState.composerFocusToken += 1
    }
}

// MARK: - Starter suggestions

private struct StarterLoadKey: Equatable {
    var projectId: String
    var ready: Bool
    var needsKey: Bool
}

/// Suggested prompts as plain rows (icon + text) under the composer; a
/// click puts the prompt in the composer. Three pulsing rows while loading.
private struct StarterList: View {
    var starters: [StarterSuggestion]?
    var loading: Bool
    var insert: (String) -> Void

    var body: some View {
        VStack(alignment: .leading, spacing: 2) {
            if let starters {
                ForEach(starters, id: \.self) { starter in
                    StarterRow(starter: starter) { insert(starter.text) }
                }
                .transition(.opacity)
            } else {
                skeleton
            }
        }
        .frame(maxWidth: .infinity, alignment: .leading)
        .animation(.easeOut(duration: 0.2), value: starters)
    }

    private var skeleton: some View {
        VStack(alignment: .leading, spacing: 2) {
            ForEach([0.46, 0.34, 0.4], id: \.self) { fraction in
                HStack(spacing: 12) {
                    SkeletonBar(width: 16, height: 16, cornerRadius: 4)
                    GeometryReader { geometry in
                        SkeletonBar(width: geometry.size.width * fraction, height: 10)
                            .frame(maxHeight: .infinity)
                    }
                }
                .frame(height: 20)
                .padding(.horizontal, 10)
                .padding(.vertical, 8)
            }
        }
        .skeletonPulse("Loading suggestions")
    }
}

private struct StarterRow: View {
    var starter: StarterSuggestion
    var action: () -> Void

    @State private var hovering = false

    var body: some View {
        Button(action: action) {
            HStack(spacing: 12) {
                Image(systemName: Icons.starter(starter.kind))
                    .font(.system(size: 14, weight: .regular))
                    .foregroundStyle(Theme.textSecondary)
                    .frame(width: 16, height: 20)
                    .accessibilityHidden(true)
                Text(starter.text)
                    .font(Theme.Font.body)
                    .foregroundStyle(Theme.textPrimary)
                    .lineLimit(1)
                    .truncationMode(.tail)
                Spacer(minLength: 0)
            }
            .padding(.horizontal, 10)
            .padding(.vertical, 8)
            .background(hovering ? Theme.surfaceRaised : Color.clear, in: RoundedRectangle(cornerRadius: Theme.Metrics.radiusSmall, style: .continuous))
            .contentShape(RoundedRectangle(cornerRadius: Theme.Metrics.radiusSmall, style: .continuous))
        }
        .buttonStyle(.plain)
        .onHover { inside in
            withAnimation(.easeOut(duration: 0.12)) { hovering = inside }
        }
        .accessibilityLabel(starter.text)
        .accessibilityHint("Inserts this prompt into the composer")
    }
}

extension StarterSuggestion {
    /// Shown when the model is not connected or `suggest/starters` came back empty.
    static func fallback(for info: ProjectInfo) -> [StarterSuggestion] {
        let command = info.validationCommands.first?.command
        return [
            StarterSuggestion(kind: "explain", text: "Explain how this project is structured"),
            StarterSuggestion(kind: "fix", text: command.map { "Run \($0) and fix any failures" } ?? "Find and fix a bug"),
            StarterSuggestion(kind: "review", text: (info.git?.dirtyFiles ?? 0) > 0 ? "Review my uncommitted changes" : "Review the most recent commit"),
        ]
    }
}

// MARK: - Index card

/// "Index ready · 310 files · generation 12" (Rebuild on hover), "Indexing
/// 120/310" with the progress ring, or the failure line with a Rebuild button.
private struct IndexCard: View {
    var project: ProjectState

    @Environment(AppState.self) private var appState
    @State private var hovering = false

    var body: some View {
        HStack(spacing: 10) {
            if isIndexing {
                ProgressRing(fraction: project.indexFraction, size: 14)
            } else {
                Image(systemName: project.hasIndexError ? Icons.warning : Icons.check)
                    .font(.system(size: 13, weight: .medium))
                    .foregroundStyle(project.hasIndexError ? Theme.danger : Theme.success)
                    .accessibilityHidden(true)
            }
            Text(project.indexSummary)
                .font(Theme.Font.secondary)
                .foregroundStyle(project.hasIndexError ? Theme.danger : Theme.textSecondary)
                .lineLimit(2)
                .fixedSize(horizontal: false, vertical: true)
            Spacer(minLength: 8)
            if !isIndexing, project.hasIndexError || hovering {
                Button("Rebuild") {
                    Task { await appState.rebuildIndex() }
                }
                .buttonStyle(.bordered)
                .controlSize(.small)
                .help("Rebuild the repository index")
            }
        }
        .padding(.horizontal, 14)
        .padding(.vertical, 10)
        .frame(minHeight: 44)
        .background(Theme.surface, in: RoundedRectangle(cornerRadius: Theme.Metrics.radius, style: .continuous))
        .overlay(
            RoundedRectangle(cornerRadius: Theme.Metrics.radius, style: .continuous)
                .strokeBorder(Theme.border, lineWidth: 1)
        )
        .onHover { inside in
            withAnimation(.easeOut(duration: 0.12)) { hovering = inside }
        }
        .accessibilityElement(children: .contain)
        .accessibilityLabel(project.indexSummary)
    }

    private var isIndexing: Bool { project.isIndexing }
}

