/**
 * `EmptyChatView` (EmptyChatView.swift): the empty chat: halftone band, ✳,
 * "Where should we begin?", the composer for the project's pending draft,
 * the generated starter suggestions and the index card (or the
 * Connect-a-model card while no API key is set), sitting slightly above the
 * vertical centre.
 */
export function EmptyChatView({ project }: EmptyChatViewProps) {
  const needsKey = useNeedsAPIKey()
  const ready = useIsReady()

  // `.task(id: StarterLoadKey(projectId:ready:needsKey:))`: re-asked when the
  // empty chat appears for another project or the backend becomes ready.
  useEffect(() => {
    useApp.getState().loadStarters(project)
  }, [project, ready, needsKey])

  const columnRef = useRef<HTMLDivElement>(null)

  return (
    <div className={styles.scroller}>
      <div className={styles.stack}>
        <HalftoneHeader />
        <div className={styles.spacer} />
        <div className={styles.columnWrap}>
          <div ref={columnRef} className={styles.column}>
            <div className={styles.hero}>
              <LogoView />
              <h1 className={styles.title}>Where should we begin?</h1>
            </div>
            <ComposerView draftFor={project} />
            <StarterList project={project} columnRef={columnRef} />
            {needsKey ? <ConnectModelCard /> : <IndexCard project={project} />}
          </div>
        </div>
        <div className={styles.spacer} />
        {/* Sit slightly above the geometric centre, like the reference. */}
        <div className={styles.lift} aria-hidden="true" />
      </div>
    </div>
  )
}

// MARK: - Starter suggestions

/// `StarterList`: suggested prompts as plain rows (icon + text) under the
/// composer, generated by `suggest/starters` (`AppState.loadStarters`); a
/// click puts the prompt in the composer. Three pulsing rows while loading.
function StarterList({ project, columnRef }: { project: ProjectState; columnRef: RefObject<HTMLDivElement | null> }) {
  const starters = useProjectValue(project, (p) => p.starters, null)
  const hintId = useId()

  /// Puts the prompt into the project's empty-state draft and focuses the
  /// composer with the caret after the prompt (NSTextView puts it at the
  /// end when its string is replaced). The draft is committed synchronously
  /// so the composer's textarea holds the prompt before it is focused: keys
  /// typed right after the click land in the composer, after the prompt,
  /// in Chromium (WebView2) and WebKit (WKWebView) alike.
  const insert = (prompt: string) => {
    const app = useApp.getState()
    flushSync(() => app.setPendingDraft(project.id, prompt))
    const textarea = columnRef.current?.querySelector('textarea')
    if (textarea) {
      textarea.focus({ preventScroll: true })
      const end = textarea.value.length
      textarea.setSelectionRange(end, end)
    }
    app.focusComposer()
  }

  // `.animation(.easeOut(duration: 0.2), value: starters)`: the rows fade in
  // (CSS) while the skeleton they replace fades out over them.
  const reducedMotion = useReducedMotion()
  const [skeletonLeaving, setSkeletonLeaving] = useState(false)
  const hadStarters = useRef(starters !== null)
  useEffect(() => {
    const arrived = starters !== null && !hadStarters.current
    hadStarters.current = starters !== null
    if (!arrived || reducedMotion) return
    setSkeletonLeaving(true)
    const timer = window.setTimeout(() => setSkeletonLeaving(false), 200)
    return () => window.clearTimeout(timer)
  }, [starters, reducedMotion])

  return (
    <div className={styles.starters}>
      <span id={hintId} className="sr-only">
        Inserts this prompt into the composer
      </span>
      {starters ? (
        starters.map((starter, index) => <StarterRow key={`${starter.kind}\u0000${starter.text}\u0000${index}`} starter={starter} hintId={hintId} onInsert={insert} />)
      ) : (
        <StarterSkeleton />
      )}
      {starters && skeletonLeaving ? (
        <div className={styles.skeletonLeaving} aria-hidden="true">
          <StarterSkeleton />
        </div>
      ) : null}
    </div>
  )
}

const SKELETON_FRACTIONS = [0.46, 0.34, 0.4]

function StarterSkeleton() {
  return (
    <Skeleton label="Loading suggestions">
      <div className={styles.skeletonRows}>
        {SKELETON_FRACTIONS.map((fraction) => (
          <div key={fraction} className={styles.skeletonRow}>
            <Skeleton.Bar width={16} height={16} radius={4} />
            <div className={styles.skeletonText}>
              <Skeleton.Bar width={`${fraction * 100}%`} height={10} />
            </div>
          </div>
        ))}
      </div>
    </Skeleton>
  )
}

const StarterRow = memo(function StarterRow({ starter, hintId, onInsert }: { starter: StarterSuggestion; hintId: string; onInsert: (prompt: string) => void }) {
  return (
    <button type="button" className={styles.starterRow} onClick={() => onInsert(starter.text)} aria-label={starter.text} aria-describedby={hintId}>
      <span className={styles.starterIcon} aria-hidden="true">
        <Icon name={starterIcon(starter.kind)} size={14} strokeWidth={1.75} />
      </span>
      <span className={styles.starterText}>{starter.text}</span>
    </button>
  )
})

// MARK: - Index card

/// `IndexCard`: "Index ready · 310 files · generation 12" (Rebuild on
/// hover), "Indexing 120/310" with the progress ring, or the failure line with a
/// Rebuild button.
function IndexCard({ project }: { project: ProjectState }) {
  const summary = useProjectValue(project, (p) => p.indexSummary, '')
  const hasError = useProjectValue(project, (p) => p.hasIndexError, false)
  const indexing = useProjectValue(project, (p) => p.isIndexing, false)
  const fraction = useProjectValue(project, (p) => p.indexFraction, null)
  const [hovering, setHovering] = useState(false)

  return (
    <div
      className={styles.indexCard}
      onMouseEnter={() => setHovering(true)}
      onMouseLeave={() => setHovering(false)}
      role="group"
      aria-label={summary}
    >
      {indexing ? (
        <ProgressRing fraction={fraction} size={14} />
      ) : (
        <Icon name={hasError ? 'warning' : 'check'} size={13} strokeWidth={2} className={hasError ? styles.indexIconError : styles.indexIconReady} />
      )}
      <span className={[styles.indexSummary, hasError ? styles.indexSummaryError : ''].filter(Boolean).join(' ')}>{summary}</span>
      <span className={styles.indexSpacer} />
      {!indexing && (hasError || hovering) ? (
        <Tooltip content="Rebuild the repository index">
          <Button size="small" onClick={() => void useApp.getState().rebuildIndex()}>
            Rebuild
          </Button>
        </Tooltip>
      ) : null}
    </div>
  )
}
